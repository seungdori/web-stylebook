const timelineFor = (id: string): StyleTimeline => {
  const timeline = styleTimeline[id];
  if (!timeline) throw new Error(`Missing style timeline metadata: ${id}`);
  return timeline;
};

const seo = (name: string, description: LocalizedText): SeoInfo => ({
  title: t(
    `${name} - Web Stylebook`,
    `${name} - Web Stylebook`,
    `${name} - Web Stylebook`,
  ),
  description,
});

const detail = (
  id: string,
  kind: StyleKind,
  name: string,
  tags: string[],
  palette: string[],
  accent: string,
  description: LocalizedText,
  summary: LocalizedText,
  promptProfile: PromptProfile,
  visualProfile: VisualProfile,
  fusionOf?: string[],
): StyleData => ({
  id,
  kind,
  route: `/pages/${id}`,
  ...timelineFor(id),
  tags,
  palette,
  accent,
  name: t(name, name, name),
  description,
  summary,
  seo: seo(name, description),
  promptProfile,
  visualProfile,
  fusionOf,
});

